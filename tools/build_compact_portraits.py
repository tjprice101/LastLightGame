"""Derive individually anchored faces without changing canonical full artwork."""
import argparse
import hashlib
import io
import json
import math
import re
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
SETTINGS = Path("Art/provenance/compact-portrait-settings.json")
MANIFEST = Path("Art/provenance/compact-portrait-intake.json")
REVISIONS = Path("src/content/compact-portrait-revisions.ts")
SOURCE = Path("public/assets/characters")
OUTPUT = Path("public/assets/character-faces")


def digest(data):
    return hashlib.sha256(data).hexdigest()


def validate_settings(settings):
    if settings.get("version") != 1 or settings.get("outputSize") != 512:
        raise ValueError("Unsupported compact portrait settings.")
    eye_line = settings.get("eyeLine")
    if not isinstance(eye_line, (int, float)) or not math.isfinite(eye_line) or not 0 < eye_line < 1:
        raise ValueError("Invalid compact portrait eye line.")
    forms = settings.get("forms")
    if not isinstance(forms, dict) or not forms:
        raise ValueError("No reviewed compact portrait forms.")
    for slug, form in forms.items():
        if not re.fullmatch(r"[a-z]+(?:-evo-[2-6])?", slug):
            raise ValueError(f"Invalid compact portrait slug: {slug}")
        if not isinstance(form, dict):
            raise ValueError(f"Invalid reviewed face anchor: {slug}")
        eye = form.get("eye")
        size = form.get("size")
        if (not isinstance(eye, list) or len(eye) != 2 or
                any(type(value) is not int or value < 0 for value in eye) or
                type(size) is not int or size < 1 or
                not re.fullmatch(r"[a-f0-9]{64}", form.get("sourceHash", ""))):
            raise ValueError(f"Invalid reviewed face anchor: {slug}")


def derive(source_bytes, form, output_size, eye_line):
    if digest(source_bytes) != form["sourceHash"]:
        raise ValueError("Portrait source changed; review its face anchor before exporting.")
    image = Image.open(io.BytesIO(source_bytes))
    if image.mode != "RGBA":
        raise ValueError("Compact portraits require canonical transparent RGBA artwork.")
    x, y = form["eye"]
    size = form["size"]
    left = round(x - size / 2)
    top = round(y - size * eye_line)
    if left < 0 or top < 0 or left + size > image.width or top + size > image.height:
        raise ValueError("Reviewed face crop exceeds the canonical artwork.")
    crop = image.crop((left, top, left + size, top + size))
    if not crop.getchannel("A").getbbox():
        raise ValueError("Reviewed face crop contains no subject pixels.")
    output = io.BytesIO()
    crop.resize((output_size, output_size), Image.Resampling.LANCZOS).save(output, format="PNG")
    return output.getvalue(), [left, top, size, size], list(image.size)


def build(root=ROOT, check=False):
    settings = json.loads((root / SETTINGS).read_text(encoding="utf-8"))
    validate_settings(settings)
    files = {}
    payloads = {}
    for slug, form in settings["forms"].items():
        source = SOURCE / f"{slug}.png"
        data, rectangle, dimensions = derive(
            (root / source).read_bytes(), form, settings["outputSize"], settings["eyeLine"])
        target = OUTPUT / f"{slug}.png"
        payloads[target] = data
        files[slug] = {
            "source": source.as_posix(),
            "sourceHash": form["sourceHash"],
            "sourceSize": dimensions,
            "eye": form["eye"],
            "crop": rectangle,
            "output": target.as_posix(),
            "outputHash": digest(data),
        }
    manifest = {
        "version": 1, "outputSize": settings["outputSize"], "eyeLine": settings["eyeLine"],
        "settingsHash": digest(json.dumps(settings, sort_keys=True, separators=(",", ":")).encode()),
        "files": files,
    }
    payloads[MANIFEST] = (json.dumps(manifest, indent=2) + "\n").encode()
    lines = ["// Generated by tools/build_compact_portraits.py; reviewed crops only.",
             "export const compactPortraitRevisions: Readonly<Record<string, string>> = {"]
    lines.extend(f"  '{slug}': '{entry['outputHash'][:16]}'," for slug, entry in sorted(files.items()))
    payloads[REVISIONS] = ("\n".join([*lines, "};", ""])).encode()
    if check:
        stale = [str(path) for path, data in payloads.items()
                 if not (root / path).is_file() or (root / path).read_bytes() != data]
        if stale:
            raise ValueError(f"Compact portrait exports are stale: {', '.join(stale)}")
    else:
        # Preflight all reviewed sources before changing any derived outputs.
        for path, data in payloads.items():
            (root / path).parent.mkdir(parents=True, exist_ok=True)
            (root / path).write_bytes(data)
    return manifest


def review(directory, root=ROOT):
    manifest = build(root, check=True)
    directory.mkdir(parents=True, exist_ok=True)
    for size in (48, 96, 512):
        for theme, background in (("dark", "#202026"), ("light", "#eeeeee")):
            cell = max(size, 160)
            row_height = size + 28
            sheet = Image.new("RGB", (cell * 6, row_height * math.ceil(len(manifest["files"]) / 6)), background)
            draw = ImageDraw.Draw(sheet)
            for index, (slug, entry) in enumerate(manifest["files"].items()):
                x, y = (index % 6) * cell, (index // 6) * row_height
                with Image.open(root / entry["output"]) as image:
                    face = image.convert("RGBA").resize((size, size), Image.Resampling.LANCZOS)
                sheet.paste(face, (x + (cell - size) // 2, y + 24), face)
                draw.text((x + 2, y + 4), slug, fill="white" if theme == "dark" else "black")
            sheet.save(directory / f"compact-faces-{size}-{theme}.png")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--apply", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--review", type=Path)
    args = parser.parse_args()
    if args.review:
        review(args.review)
    else:
        manifest = build(check=args.check)
        print(f"Compact portraits: {len(manifest['files'])} reviewed forms {'verified' if args.check else 'exported'}.")


if __name__ == "__main__":
    main()
