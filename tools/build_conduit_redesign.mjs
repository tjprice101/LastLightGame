import { readFileSync, writeFileSync } from 'node:fs';

const source = readFileSync(new URL('../docs/conduit-redesign.md', import.meta.url), 'utf8');
const rows = source.split(/\r?\n/).filter(line => /^\| (?:C|R|L|O|M)\d+ \|/.test(line));
if (rows.length !== 133) throw new Error(`Expected 133 Conduit designs, got ${rows.length}.`);
const entries = rows.map(line => {
  const cells = line.split('|').map(cell => cell.trim());
  const id = cells[2].match(/`([^`]+)`/)?.[1];
  if (!id) throw new Error(`Missing ID: ${line}`);
  const description = cells[cells[1].startsWith('O') ? 4 : 3];
  const ranges = Array.from(description.matchAll(/([+-]?\d+(?:\.\d+)?)(%?)\s*->\s*([+-]?\d+(?:\.\d+)?)(%?)/g),
    match => ({ base: Number(match[1]), maximum: Number(match[3]), percent: !!(match[2] || match[4]),
      step: !match[2] && !match[4] && ((Number(match[1]) === 1 && Number(match[3]) === 2) ||
        (Number(match[1]) === 3 && Number(match[3]) === 2) || (Number(match[1]) === 4 && Number(match[3]) === 5)) }));
  return [id, { description, ranges }];
});
if (new Set(entries.map(([id]) => id)).size !== 133) throw new Error('Duplicate Conduit design ID.');
const output = `// Generated by tools/build_conduit_redesign.mjs from the approved roster.
export interface ConduitRange { base: number; maximum: number; percent: boolean; step: boolean }
export interface ConduitDesign { description: string; ranges: readonly ConduitRange[] }
export const conduitRedesign: Readonly<Record<string, ConduitDesign>> = ${JSON.stringify(Object.fromEntries(entries), null, 2)};

export function redesignValue(level: number, base: number, maximum: number): number {
  if (!Number.isInteger(level) || level < 0 || level > 5) throw new Error('Invalid Conduit effect level.');
  return base + (maximum - base) * level / 5;
}
export function redesignStep(level: number, base: number, maximum: number): number {
  redesignValue(level, base, maximum);
  return level < 3 ? base : maximum;
}
export function redesignEffect(id: string, level = 0): string {
  const design = conduitRedesign[id];
  if (!design) throw new Error('Missing redesigned Conduit definition: ' + id);
  redesignValue(level, 0, 0);
  let index = 0;
  return design.description.replace(/([+-]?\\d+(?:\\.\\d+)?)(%?)\\s*->\\s*([+-]?\\d+(?:\\.\\d+)?)(%?)/g,
    (_match, first: string, leftUnit: string, _last: string, rightUnit: string) => {
      const range = design.ranges[index++];
      const amount = range.step ? redesignStep(level, range.base, range.maximum) : redesignValue(level, range.base, range.maximum);
      return (first.startsWith('+') && amount >= 0 ? '+' : '') +
        Number(amount.toFixed(8)).toString() + (leftUnit || rightUnit);
    });
}
`;
writeFileSync(new URL('../src/content/conduit-redesign.ts', import.meta.url), output);
