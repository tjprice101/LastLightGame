import { readFileSync, writeFileSync } from 'node:fs';

const read = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');
const sourceFiles = [
  'src/content/conduits.ts',
  'src/content/kit-conduits.ts',
  'src/content/calamitic-conduits.ts',
];
const idsByName = new Map();
for (const file of sourceFiles) {
  const source = read(file);
  for (const [, id, name] of source.matchAll(/\bid:\s*'([^']+)'\s*,\s*name:\s*'([^']+)'/g)) idsByName.set(name, id);
  for (const [, id, name] of source.matchAll(/\bid:\s*'([^']+)'\s*,\s*name:\s*"([^"]+)"/g)) idsByName.set(name, id);
}
const masters = read('src/content/master-conduits.ts');
for (const [, character, slot, name] of masters.matchAll(/master\('([^']+)'\s*,\s*(\d+)\s*,\s*'([^']+)'/g)) {
  idsByName.set(name, `master-${character}-${slot}`);
}

const catalog = read('docs/conduit-catalog.txt');
const entries = [...catalog.matchAll(
  /^Name: (.+)\r?\nRarity: (.+)\r?\nElement: (.+)\r?\nAbility \(Default Value\): ([\s\S]*?)(?=\r?\n\r?\n|(?![\s\S]))/gm,
)].map(([, name, rarity, element, ability]) => ({
  id: idsByName.get(name) ?? (name === "World-Eater's Orrery" ? 'calamitic-world-eater-orrery' : undefined),
  name,
  rarity,
  element,
  ability: ability.trim().replace(/\s+/g, ' '),
}));
if (entries.length !== 138 || entries.some(entry => !entry.id) ||
    new Set(entries.map(entry => entry.name)).size !== 138 || new Set(entries.map(entry => entry.id)).size !== 138) {
  const unresolved = entries.filter(entry => !entry.id).map(entry => entry.name);
  throw new Error(`Expected 138 unique catalog entries; unresolved: ${unresolved.join(', ')}`);
}

const output = `// Generated by tools/build_phase_zero_conduit_catalog.mjs from docs/conduit-catalog.txt.
export interface ApprovedConduitEntry {
  name: string;
  rarity: string;
  element: string;
  ability: string;
}

export const approvedConduitCatalog: Readonly<Record<string, ApprovedConduitEntry>> = ${JSON.stringify(
  Object.fromEntries(entries.map(({ id, ...entry }) => [id, entry])), null, 2,
)};

export function approvedConduitAbility(id: string): string | undefined {
  return approvedConduitCatalog[id]?.ability;
}
`;
writeFileSync(new URL('../src/content/phase-zero-conduit-catalog.ts', import.meta.url), output);
