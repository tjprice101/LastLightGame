"""Archive, review and reproduce the 45 delivered Phase 1 Elemental War images."""
import argparse
from hashlib import sha256
from io import BytesIO
import json
from pathlib import Path
import shutil

import numpy as np
from PIL import Image, ImageDraw

from build_phase1_war_art import DESIGNS
from intake_character_refresh import clean
from prepare_art import ROOT, standardize_sprite

SETTINGS = ROOT / "Art" / "provenance" / "phase1-war-art-settings.json"
MANIFEST = ROOT / "Art" / "provenance" / "phase1-war-art-intake.json"
REVISIONS = ROOT / "src" / "content" / "phase1-war-art-revisions.ts"
SCENERY = ("banners", "backgrounds")


def assets(root=None):
    root = root or ROOT
    rows = []
    for design in DESIGNS:
        slug, name = design["slug"], design["name"]
        rows.extend((f"{title}, {name}.png", "characters",
                     slug + (f"-evo-{index + 1}" if index else ""))
                    for index, title in enumerate(design["titles"]))
        rows.extend((f"{heading} {title}.png", "abilities", f"{slug}-{action}")
                    for (heading, title, _), action in
                    zip(design["icons"], ("passive", "skill1", "skill2", "ultimate")))
        rows.extend((f"{title}.png", "master-conduits", f"master-{slug}-{index}")
                    for index, (title, _, _) in enumerate(design["masters"], 1))
        rows.extend(((f"{name} trial header.png", "banners", f"elemental-war-{slug}-banner"),
                     (f"{name} trial arena.png", "backgrounds", f"elemental-war-{slug}-arena")))
    return [(filename, category, asset,
             root / "Art" / "source" / "phase1-war" / category / filename,
             root / "public" / "assets" / category / f"{asset}.png")
            for filename, category, asset in rows]


def digest(path):
    return sha256(path.read_bytes()).hexdigest()


def revision_source():
    lines = ["// Generated by tools/intake_phase1_war_art.py after reviewed exports.",
             "export const phase1WarArtRevisions: Readonly<Record<string, string>> = {"]
    for _, _, _, _, runtime in assets():
        path = runtime.relative_to(ROOT / "public" / "assets").as_posix()
        lines.append(f"  '{path}': '{digest(runtime)[:16]}',")
    return "\n".join([*lines, "};", ""])


def initialize_settings():
    if SETTINGS.exists():
        raise FileExistsError(SETTINGS)
    settings = {}
    for filename, category, asset, archived, _ in assets():
        source = ROOT / filename
        if not source.exists():
            source = archived
        with Image.open(source) as image:
            if category in SCENERY:
                settings[asset] = {"processing": "opaque scenery; unchanged source bytes",
                                   "review": ""}
                continue
            rgb = np.asarray(image.convert("RGB"))
            corners = np.concatenate((rgb[:4, :4].reshape(-1, 3), rgb[-4:, :4].reshape(-1, 3),
                                      rgb[:4, -4:].reshape(-1, 3), rgb[-4:, -4:].reshape(-1, 3)))
            settings[asset] = {
                "keys": [np.median(corners, axis=0).astype(int).tolist()],
                "row_gradient": True, "radius": 34, "border_only": True,
                "background_seeds": [], "foreground_polygons": [],
                "edge_cleanup": {"source_pixels": 1, "distance_ramp": 32},
                "review": "",
            }
    SETTINGS.write_text(json.dumps(settings, indent=2) + "\n", encoding="utf-8")


def clean_source(image, settings):
    cleaned = clean(image, settings)
    if image.convert("RGBA").getextrema()[3][0] == 255:
        draw = ImageDraw.Draw(cleaned)
        for polygon in settings.get("discarded_frame_regions", []):
            draw.polygon([(round(x * image.width), round(y * image.height)) for x, y in polygon],
                         fill=(0, 0, 0, 0))
    return cleaned


def prepare(source, settings, category, canvas_size=None, content_size=None):
    if category in SCENERY:
        with Image.open(source) as image:
            if image.convert("RGBA").getextrema()[3][0] < 255:
                raise ValueError(f"Trial scenery must be opaque: {source}")
        return source.read_bytes()
    with Image.open(source) as image:
        cleaned = clean_source(image, settings)
        output = standardize_sprite(cleaned,
                                    canvas_size or (960 if category == "characters" else 256),
                                    content_size or (864 if category == "characters" else 224))
    buffer = BytesIO()
    output.save(buffer, format="PNG", optimize=True)
    return buffer.getvalue()


def reviewed_source(asset):
    match = next((row for row in assets() if row[2] == asset and row[1] not in SCENERY), None)
    if match is None:
        return None
    _, category, _, archived, _ = match
    if archived.is_file():
        return archived, category
    if MANIFEST.exists():
        raise FileNotFoundError(f"Installed Phase 1 source is missing: {archived}")
    return None


def preflight(root=None, settings_path=SETTINGS, manifest_path=MANIFEST):
    root = root or ROOT
    settings = json.loads(settings_path.read_text(encoding="utf-8"))
    rows = assets(root)
    if set(settings) != {row[2] for row in rows} or len(rows) != 45:
        raise ValueError("Phase 1 settings must cover exactly 45 delivered assets.")
    previous = json.loads(manifest_path.read_text(encoding="utf-8")) if manifest_path.exists() else {}
    old_records = {row["asset"]: row for row in previous.get("assets", [])}
    if old_records and set(old_records) != set(settings):
        raise ValueError("Installed Phase 1 manifest coverage changed.")
    planned = []
    for filename, category, asset, archived, runtime in rows:
        incoming = root / filename
        source = incoming if incoming.is_file() else archived
        if not source.is_file():
            raise FileNotFoundError(source)
        source_hash = digest(source)
        if archived.exists() and digest(archived) != source_hash:
            raise FileExistsError(f"Conflicting archived original: {archived}")
        old = old_records.get(asset)
        if old and old["source_sha256"] != source_hash:
            raise ValueError(f"Source changed: {asset}")
        if runtime.exists() and (not old or digest(runtime) != old["runtime_sha256"]):
            raise FileExistsError(f"Untracked or changed runtime: {runtime}")
        config = settings[asset]
        if category not in SCENERY and (not config.get("border_only") or not config.get("keys")):
            raise ValueError(f"Missing connected source key: {asset}")
        output = prepare(source, config, category)
        with Image.open(source) as image:
            alpha = image.convert("RGBA").getextrema()[3][0] < 255
            dimensions = list(image.size)
        record = {"incoming": filename, "category": category, "asset": asset,
                  "source": archived.relative_to(root).as_posix(), "source_sha256": source_hash,
                  "source_dimensions": dimensions, "source_alpha_authoritative": alpha,
                  "runtime": runtime.relative_to(root).as_posix(),
                  "runtime_sha256": sha256(output).hexdigest(), "settings": config}
        planned.append((source, archived, runtime, output, record))
    return planned


def review(directory, planned):
    directory.mkdir(parents=True, exist_ok=True)
    for _, _, _, output, record in planned:
        (directory / f"{record['asset']}.png").write_bytes(output)
    for design in DESIGNS:
        rows = [row for row in planned if design["slug"] in row[-1]["asset"]]
        for label, color in (("dark", "#25252b"), ("light", "#eeeeee")):
            sheet = Image.new("RGB", (1500, 1185), color)
            draw = ImageDraw.Draw(sheet)
            for index, (source, _, _, output, record) in enumerate(rows):
                image = Image.open(BytesIO(output)).convert("RGBA")
                image.thumbnail((290, 350))
                x, y = index % 5 * 300, index // 5 * 395
                sheet.paste(image, (x + (300 - image.width) // 2, y), image)
                draw.text((x + 4, y + 357), record["asset"], fill="#888888")
                if record["category"] not in SCENERY:
                    with Image.open(source) as original:
                        full = clean_source(original, record["settings"])
                    full_sheet = Image.new("RGB", full.size, color)
                    full_sheet.paste(full, (0, 0), full)
                    full_sheet.save(directory / f"{record['asset']}-source-{label}.png")
            sheet.save(directory / f"{design['slug']}-{label}.png")


def intake(apply=False, reviewed=False, directory=None):
    planned = preflight()
    if directory:
        review(directory, planned)
    if not apply:
        print(f"Prepared {len(planned)} assets; originals unchanged.")
        return
    if not reviewed or any(not row[-1]["settings"].get("review") for row in planned):
        raise ValueError("Install only after recorded dark/light/source-resolution review.")
    for source, archived, runtime, output, record in planned:
        archived.parent.mkdir(parents=True, exist_ok=True)
        runtime.parent.mkdir(parents=True, exist_ok=True)
        if not archived.exists():
            shutil.copyfile(source, archived)
        if digest(archived) != record["source_sha256"]:
            raise RuntimeError(f"Archive verification failed: {archived}")
        runtime.write_bytes(output)
    for _, archived, runtime, _, record in planned:
        if digest(archived) != record["source_sha256"] or digest(runtime) != record["runtime_sha256"]:
            raise RuntimeError("Archive/export verification failed; incoming files retained.")
    MANIFEST.write_text(json.dumps({"asset_count": 45, "assets": [row[-1] for row in planned]},
                                   indent=2) + "\n", encoding="utf-8")
    REVISIONS.write_text(revision_source(), encoding="utf-8")
    for _, _, _, _, record in planned:
        incoming = ROOT / record["incoming"]
        if incoming.exists():
            incoming.unlink()
    print("Installed 45 assets; source bytes verified before root cleanup.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--init-settings", action="store_true")
    parser.add_argument("--review", type=Path)
    parser.add_argument("--apply", action="store_true")
    parser.add_argument("--reviewed", action="store_true")
    parser.add_argument("--write-revisions", action="store_true")
    args = parser.parse_args()
    if args.init_settings:
        initialize_settings()
    elif args.write_revisions:
        REVISIONS.write_text(revision_source(), encoding="utf-8")
    else:
        intake(args.apply, args.reviewed, args.review)
