"""Generate content-versioned URLs for supplied Master Conduit artwork."""

import argparse
from hashlib import sha256
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "src" / "content" / "master-conduit-art-revisions.ts"
EXPECTED = 50


def revision_source():
    assets = sorted((ROOT / "public" / "assets" / "master-conduits").glob("*.png"))
    if len(assets) != EXPECTED:
        raise ValueError(f"Expected {EXPECTED} Master Conduit images, found {len(assets)}.")
    lines = ["// Generated by tools/master_conduit_art_revisions.py; regenerate after Master Conduit exports.",
             "export const masterConduitArtRevisions: Readonly<Record<string, string>> = {"]
    for asset in assets:
        revision = sha256(asset.read_bytes()).hexdigest()[:16]
        lines.append(f"  '{asset.stem}': '{revision}',")
    return "\n".join([*lines, "};", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    if args.write:
        OUTPUT.write_text(revision_source(), encoding="utf-8")
        print("Master Conduit artwork revisions generated.")
    elif not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != revision_source():
        raise ValueError("Master Conduit revisions are stale. Run with --write after reviewed exports.")
    else:
        print("Master Conduit artwork revisions match runtime bytes.")
